import { readFile, writeFile, readdir } from "node:fs/promises";

const root = new URL("../", import.meta.url);
const directory = new URL("supabase/migrations/", root);
const files = (await readdir(directory)).filter((file) =>
  file.endsWith("_round4_mission_catalogue.sql"),
);
if (files.length !== 1)
  throw new Error("Expected exactly one round4_mission_catalogue migration.");
const load = async (name) =>
  JSON.parse(await readFile(new URL(`data/round4/${name}.json`, root), "utf8"));
const missions = await load("missions");
const links = await load("interest-links");
const books = await load("learning-shelf");
if (missions.length !== 1257 || books.length !== 57 || links.length !== 44)
  throw new Error("Extract and validate the full Round 4 workbook first.");

let sql = `-- Round 4: complete, non-destructive catalogue upsert.
-- Source: Kelly's November 25 workbook; generated by scripts/build-round4-seed.mjs.
-- Retains all historical IDs, private missions, completed focuses and reflections.
begin;
create temporary table round4_missions on commit drop as
select * from jsonb_populate_recordset(null::public.missions,$round4$${JSON.stringify(missions)}$round4$);
do $$ begin
  if exists(select 1 from round4_missions n join public.missions m on m.id=n.id where m.user_id is not null) then
    raise exception 'A Round 4 catalogue ID conflicts with a private mission; import cancelled.';
  end if;
end $$;
`;
const columns = Object.keys(missions[0]);
sql += `insert into public.missions(${columns.join(",")}) select ${columns.join(",")} from round4_missions
on conflict(id) do update set ${columns
  .filter((column) => column !== "id")
  .map((column) => `${column}=excluded.${column}`)
  .join(",")},updated_at=now()
where public.missions.user_id is null
and (${columns
  .filter((column) => column !== "id")
  .map((column) => `public.missions.${column}`)
  .join(",")})
  is distinct from (${columns
    .filter((column) => column !== "id")
    .map((column) => `excluded.${column}`)
    .join(",")});
`;
for (const [table, rows, keys] of [
  ["interest_links", links, ["interest", "similar_interest"]],
  ["learning_shelf", books, ["id"]],
]) {
  const fields = Object.keys(rows[0]);
  sql += `insert into public.${table}(${fields.join(",")}) select ${fields.join(",")} from jsonb_populate_recordset(null::public.${table},$round4$${JSON.stringify(rows)}$round4$)
on conflict(${keys.join(",")}) do update set ${fields
    .filter((field) => !keys.includes(field))
    .map((field) => `${field}=excluded.${field}`)
    .join(",")};
`;
}
sql += "commit;\n";
await writeFile(new URL(files[0], directory), sql);
console.log(
  `Built ${files[0]} with ${missions.length} missions; no database changed.`,
);
