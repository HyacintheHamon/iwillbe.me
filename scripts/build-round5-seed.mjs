import { readFile, writeFile, readdir } from "node:fs/promises";

const root = new URL("../", import.meta.url);
const directory = new URL("supabase/migrations/", root);
const files = (await readdir(directory)).filter((file) =>
  file.endsWith("_round5_mission_catalogue.sql"),
);
if (files.length !== 1)
  throw new Error("Expected exactly one round5_mission_catalogue migration.");
const load = async (name) =>
  JSON.parse(await readFile(new URL(`data/round5/${name}.json`, root), "utf8"));
const missions = await load("missions");
const links = await load("interest-links");
const books = await load("learning-shelf");
if (missions.length !== 1284 || books.length !== 59 || links.length !== 44)
  throw new Error("Extract and validate the full mission library v2 first.");

let sql = `-- Mission library v2: complete, non-destructive catalogue upsert.
-- Source: Kelly's November 26 workbook; generated by scripts/build-round5-seed.mjs.
-- Retains all historical IDs, private missions, completed focuses and reflections.
begin;
insert into public.priority_words(name,position) values('joyful',38)
on conflict(name) do update set position=excluded.position;
alter table public.missions drop constraint if exists missions_ages_allowed;
alter table public.missions add constraint missions_ages_allowed
check(ages <@ array['under 6','6–12','teens','adults']::text[]);
comment on column public.missions.ages is 'Source age labels. For adults-only families, exclude untagged kid missions because those were written for younger children.';
create temporary table round5_missions on commit drop as
select * from jsonb_populate_recordset(null::public.missions,$round5$${JSON.stringify(missions)}$round5$);
do $$ begin
  if exists(select 1 from round5_missions n join public.missions m on m.id=n.id where m.user_id is not null) then
    raise exception 'A mission library v2 ID conflicts with a private mission; import cancelled.';
  end if;
  if (select count(*) from round5_missions) <> 1284
     or (select count(*) from round5_missions where 'joyful'=any(priorities)) <> 43
     or (select count(*) from round5_missions where 'adults'=any(ages)) <> 9 then
    raise exception 'Mission library v2 catalogue validation failed; import cancelled.';
  end if;
end $$;
`;
const columns = Object.keys(missions[0]);
sql += `insert into public.missions(${columns.join(",")}) select ${columns.join(",")} from round5_missions
on conflict(id) do update set ${columns
  .filter((column) => column !== "id")
  .map((column) => `${column}=excluded.${column}`)
  .join(",")},updated_at=now()
where public.missions.user_id is null
and (${columns
  .filter((column) => column !== "id")
  .map((column) => `public.missions.${column}`)
  .join(",")})
  is distinct from (${columns
    .filter((column) => column !== "id")
    .map((column) => `excluded.${column}`)
    .join(",")});
`;
for (const [table, rows, keys] of [
  ["interest_links", links, ["interest", "similar_interest"]],
  ["learning_shelf", books, ["id"]],
]) {
  const fields = Object.keys(rows[0]);
  sql += `insert into public.${table}(${fields.join(",")}) select ${fields.join(",")} from jsonb_populate_recordset(null::public.${table},$round5$${JSON.stringify(rows)}$round5$)
on conflict(${keys.join(",")}) do update set ${fields
    .filter((field) => !keys.includes(field))
    .map((field) => `${field}=excluded.${field}`)
    .join(",")};
`;
}
sql += "commit;\n";
await writeFile(new URL(files[0], directory), sql);
console.log(
  `Built ${files[0]} with ${missions.length} missions; no database changed.`,
);
