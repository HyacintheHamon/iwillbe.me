import { readFile, writeFile, readdir } from "node:fs/promises";

const root = new URL("../", import.meta.url);
const directory = new URL("supabase/migrations/", root);
const files = (await readdir(directory)).filter((file) =>
  file.endsWith("_round3_mission_catalogue.sql"),
);
if (files.length !== 1)
  throw new Error(
    "Create exactly one round3_mission_catalogue migration with the Supabase CLI first.",
  );
const missions = JSON.parse(
  await readFile(new URL("data/round3/missions.json", root), "utf8"),
);
const links = JSON.parse(
  await readFile(new URL("data/round3/interest-links.json", root), "utf8"),
);
const books = JSON.parse(
  await readFile(new URL("data/round3/learning-shelf.json", root), "utf8"),
);

let sql = `-- Round 3: additive metadata and a complete, non-destructive catalogue upsert.
-- Source: Kelly's November 18 workbook; generated by scripts/build-round3-seed.mjs.
-- Historical mission IDs, user-owned missions and all user history are preserved.
alter table public.missions add column if not exists ages text[] not null default '{}';
alter table public.missions add column if not exists family_id text not null default '';
alter table public.missions add column if not exists theme text not null default '';
alter table public.missions add constraint missions_ages_allowed check(ages <@ array['under 6','6–12','teens']::text[]);
alter table public.missions add constraint missions_theme_allowed check(theme in ('','moving','eating well','sleep','water','rest and stress','check-ups','cutting back'));
comment on column public.missions.ages is 'Empty means all ages. Values use the source workbook labels.';
comment on column public.missions.family_id is 'Same idea in easy, normal and stretch. Separate extra ideas retain their suffix.';
comment on column public.missions.theme is 'Healthy theme used for daily rotation; empty for unclassified missions.';

`;
sql += `create temporary table round3_missions as select * from jsonb_populate_recordset(null::public.missions,$round3$${JSON.stringify(missions)}$round3$);\n`;
sql += `do $$ begin
  if exists(select 1 from round3_missions n join public.missions m on m.id=n.id where m.user_id is not null) then
    raise exception 'A Round 3 catalogue ID conflicts with a private mission; import cancelled.';
  end if;
end $$;\n`;
const columns = Object.keys(missions[0]);
sql += `insert into public.missions(${columns.join(",")}) select ${columns.join(",")} from round3_missions
on conflict(id) do update set ${columns
  .filter((column) => column !== "id")
  .map((column) => `${column}=excluded.${column}`)
  .join(",")},updated_at=now()
where public.missions.user_id is null;
drop table round3_missions;
`;
for (const [table, rows, keys] of [
  ["interest_links", links, ["interest", "similar_interest"]],
  ["learning_shelf", books, ["id"]],
]) {
  const fields = Object.keys(rows[0]);
  sql += `insert into public.${table}(${fields.join(",")}) select ${fields.join(",")} from jsonb_populate_recordset(null::public.${table},$round3$${JSON.stringify(rows)}$round3$)
on conflict(${keys.join(",")}) do update set ${fields
    .filter((field) => !keys.includes(field))
    .map((field) => `${field}=excluded.${field}`)
    .join(",")};\n`;
}
await writeFile(new URL(files[0], directory), sql);
console.log(
  `Built ${files[0]} with ${missions.length} missions; no database changed.`,
);
